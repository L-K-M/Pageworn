#!/usr/bin/env python3
"""Generate the synthetic, redistributable audio fixtures for Pageworn tests.

Usage (from the repository root):

    python3 fixtures/generate.py              # regenerate every fixture
    python3 fixtures/generate.py --only <id>  # regenerate one fixture

Everything is written under fixtures/out/ (gitignored).  The manifest is
written to fixtures/out/assets/fixtures/manifest.json and to the committed
fixtures/manifest.json.  Requires Python 3 and ffmpeg/ffprobe 9.x on PATH.

The signal is identical for every fixture: a continuous 180 Hz sine bed at
amplitude 0.05 plus 400 ms cues at amplitude 0.5 with 10 ms linear fades.
The PCM is rendered in Python and written as a 16-bit WAV, so cue placement
is sample-exact before ffmpeg encodes it.
"""

