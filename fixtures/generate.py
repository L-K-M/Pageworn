def run_docker_awb(wav: Path, out: Path, cmds: list[str]) -> None:
    inner = [
        "-hide_banner",
        "-loglevel",
        "error",
        "-y",
        "-f",
        "wav",
        "-i",
        "-",
        "-ar",
        "16000",
        "-c:a",
        "libvo_amrwbenc",
        "-b:a",
        "23.85k",
        "-f",
        "amr",
        "-",
    ]
    last_error = "docker is not available"
    for image in AWB_IMAGES:
        cmd = ["docker", "run", "--rm", "-i", "--entrypoint", "ffmpeg", image, *inner]
        try:
            with open(wav, "rb") as fin, open(out, "wb") as fout:
                proc = subprocess.run(
                    cmd,
                    stdin=fin,
                    stdout=fout,
                    stderr=subprocess.PIPE,
                    timeout=1200,
                )
        except (subprocess.TimeoutExpired, FileNotFoundError, OSError) as exc:
            last_error = f"{image}: {exc}"
            continue
        if proc.returncode == 0:
            recorded = shlex.join(cmd) + f" < {rel(wav)} > {rel(out)}"
            cmds.append(recorded)
            return
        err = proc.stderr.decode("utf-8", "replace").strip()
        last_error = f"{image}: {clean_error_line(err.splitlines()[-1]) if err else 'exit ' + str(proc.returncode)}"
    raise RuntimeError(f"no AMR-WB encoder route ({last_error})")


