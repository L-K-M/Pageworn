def render_samples(
    total_samples: int,
    sample_rate: int,
    cue_times: list[float],
    freq_start: int = 0,
) -> array:
    """Render mono 16-bit PCM: 180 Hz bed plus the given cues."""
    # The bed period is a whole number of samples, so tile one period in C.
    period_len = sample_rate // math.gcd(sample_rate, BED_FREQ)
    period = array(
        "h",
        (
            int(round(32767.0 * BED_AMP * math.sin(2.0 * math.pi * BED_FREQ * i / sample_rate)))
            for i in range(period_len)
        ),
    )
    samples = period * (total_samples // period_len) + period[: total_samples % period_len]

    fade = max(1, int(round(FADE_SECONDS * sample_rate)))
    cue_len = int(round(CUE_SECONDS * sample_rate))
    for index, t in enumerate(cue_times):
        freq = CUE_FREQS[freq_start + index]
        start = int(round(t * sample_rate))
        for j in range(cue_len):
            n = start + j
            if n >= total_samples:
                break
            if j < fade:
                gain = j / fade
            elif j >= cue_len - fade:
                gain = (cue_len - j) / fade
            else:
                gain = 1.0
            value = BED_AMP * math.sin(2.0 * math.pi * BED_FREQ * n / sample_rate)
            value += CUE_AMP * gain * math.sin(2.0 * math.pi * freq * j / sample_rate)
            samples[n] = int(round(32767.0 * value))
    return samples


def write_wav(path: Path, samples: array, sample_rate: int) -> None:
    if sys.byteorder == "big":
        samples.byteswap()
    with wave.open(str(path), "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(sample_rate)
        wav.writeframes(samples.tobytes())


def ensure_wav(
    key: str,
    seconds: float,
    sample_rate: int,
    cue_times: list[float],
    freq_start: int = 0,
) -> Path:
    path = WORK_DIR / f"{key}.wav"
    if not path.exists():
        samples = render_samples(
            int(round(seconds * sample_rate)), sample_rate, cue_times, freq_start
        )
        write_wav(path, samples, sample_rate)
    return path


def rel(path: Path) -> str:
    return path.relative_to(OUT_DIR).as_posix()


