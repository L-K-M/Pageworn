# Cue frequencies in time order: cue 0 is 700 Hz, cue 1 is 900 Hz, ...
CUE_FREQS = [700, 900, 1100, 1300, 1500, 1700, 1900, 2100, 2300, 2500]
BED_FREQ = 180
BED_AMP = 0.05
CUE_AMP = 0.5
CUE_SECONDS = 0.400
FADE_SECONDS = 0.010

FFMPEG = shutil.which("ffmpeg")
FFPROBE = shutil.which("ffprobe")

