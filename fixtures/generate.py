def clean_error_line(line: str) -> str:
    """Strip volatile prefixes and pointer values from an ffmpeg log line."""
    line = re.sub(r"^\[[^]]*\]\s*", "", line.strip())
    line = re.sub(r"@ 0x[0-9a-fA-F]+", "", line)
    line = line.replace(str(OUT_DIR), ".")
    return line.strip()


def ffmpeg_error(stderr: str) -> str:
    lines = [clean_error_line(line) for line in stderr.strip().splitlines()]
    lines = [line for line in lines if line]
    if not lines:
        return "ffmpeg failed"
    preferred = (
        "muxing codec",
        "unknown encoder",
        "not recognized",
        "unsupported",
        "could not write header",
        "error initializing",
    )
    for key in preferred:
        for line in lines:
            if key in line.lower():
                return line
    return lines[-1]


def ffmpeg_cmd(args: list[str], cmds: list[str]) -> str:
    """Run ffmpeg with cwd=fixtures/out and record the exact command line."""
    # Bit-exact output: no encoder version tags, fixed Ogg serials and Matroska IDs, so a
    # regeneration with the same ffmpeg reproduces the checksums in the manifest.
    cmd = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", *args[:-1],
           "-fflags", "+bitexact", "-flags:a", "+bitexact", args[-1]]
    proc = subprocess.run(
        [FFMPEG, *cmd[1:]], cwd=str(OUT_DIR), capture_output=True, text=True
    )
    if proc.returncode != 0:
        raise RuntimeError(ffmpeg_error(proc.stderr))
    recorded = shlex.join(cmd)
    cmds.append(recorded)
    return recorded


def probe_audio(path: Path) -> dict:
    proc = subprocess.run(
        [
            FFPROBE,
            "-v",
            "error",
            "-select_streams",
            "a:0",
            "-show_entries",
            "format=format_name,duration",
            "-show_entries",
            "stream=codec_name,sample_rate",
            "-of",
            "json",
            str(path),
        ],
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        raise RuntimeError(ffmpeg_error(proc.stderr))
    data = json.loads(proc.stdout)
    return {"format": data["format"], "stream": data["streams"][0]}


def has_chapters(path: Path) -> bool:
    proc = subprocess.run(
        [
            FFPROBE,
            "-v",
            "error",
            "-show_entries",
            "chapter=start",
            "-of",
            "json",
            str(path),
        ],
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        return False
    try:
        return bool(json.loads(proc.stdout).get("chapters"))
    except (ValueError, AttributeError):
        return False


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def file_entry(path: Path) -> dict:
    info = probe_audio(path)
    fmt = info["format"]
    stream = info["stream"]
    return {
        "name": path.name,
        "extension": path.suffix.lstrip("."),
        "container": fmt["format_name"],
        "codec": stream["codec_name"],
        "duration_ms": int(round(float(fmt["duration"]) * 1000)),
        "sample_rate": int(stream["sample_rate"]),
        "size_bytes": path.stat().st_size,
        "sha256": sha256_file(path),
    }


def cues_manifest(cue_times: list[float]) -> list[dict]:
    return [
        {"at_ms": int(round(t * 1000)), "freq_hz": CUE_FREQS[i]}
        for i, t in enumerate(cue_times)
    ]


def make_entry(
    fixture_id: str,
    cmds: list[str],
    files: list[dict],
    nominal_ms: int,
    cue_times: list[float],
    **extra,
) -> dict:
    entry = {
        "id": fixture_id,
        "status": "generated",
        "files": files,
        "nominal_duration_ms": nominal_ms,
        "cues": cues_manifest(cue_times),
        "command": " && ".join(cmds),
    }
    entry.update(extra)
    return entry


def write_metadata(path: Path, tags: dict, chapters: list[tuple[str, int, int]]) -> None:
    lines = [";FFMETADATA1"]
    for key, value in tags.items():
        lines.append(f"{key}={value}")
    for title, start, end in chapters:
        lines.extend(
            [
                "[CHAPTER]",
                "TIMEBASE=1/1000",
                f"START={start * 1000}",
                f"END={end * 1000}",
                f"title={title}",
            ]
        )
    path.write_text("\n".join(lines) + "\n")


