for _spec in FORMAT_SPECS:
    BUILDERS[_spec["id"]] = lambda cmds, _spec=_spec: build_format_sample(_spec, cmds)

ALL_IDS = [
    "boundary-book",
    "single-m4b",
    "no-chapters-single",
    "no-chapters-multi",
    *[spec["id"] for spec in FORMAT_SPECS],
    "fmt-mp3-vbr-long",
]


def ffmpeg_version_line() -> str:
    proc = subprocess.run([FFMPEG, "-version"], capture_output=True, text=True)
    return proc.stdout.splitlines()[0]


def write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n")


def load_previous_manifest() -> dict:
    if not COMMITTED_MANIFEST.exists():
        return {}
    try:
        return json.loads(COMMITTED_MANIFEST.read_text())
    except ValueError:
        return {}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", metavar="ID", help="generate only this fixture id")
    args = parser.parse_args()

    if args.only and args.only not in ALL_IDS:
        parser.error(f"unknown fixture id: {args.only}")

    if FFMPEG is None or FFPROBE is None:
        print("error: ffmpeg and ffprobe must be on PATH", file=sys.stderr)
        return 2

    if args.only is None:
        if OUT_DIR.exists():
            shutil.rmtree(OUT_DIR)
        WORK_DIR.mkdir(parents=True)
        previous: dict[str, dict] = {}
    else:
        WORK_DIR.mkdir(parents=True, exist_ok=True)
        previous = {e["id"]: e for e in load_previous_manifest().get("fixtures", [])}

    entries = []
    for fid in ALL_IDS:
        if args.only is None or fid == args.only:
            print(f"== {fid}")
            cmds: list[str] = []
            try:
                entry = BUILDERS[fid](cmds)
                entry["status"] = "generated"
            except Exception as exc:  # noqa: BLE001 - record and continue
                shutil.rmtree(ASSETS_DIR / fid, ignore_errors=True)
                entry = {"id": fid, "status": "not-generated", "reason": str(exc)}
                if fid.startswith("fmt-"):
                    entry["server_release_admitting_extension"] = SERVER_RELEASE
                if cmds:
                    entry["command"] = " && ".join(cmds)
                print(f"   not generated: {exc}", file=sys.stderr)
            entries.append(entry)
        else:
            entry = previous.get(fid)
            if entry is None:
                entry = {
                    "id": fid,
                    "status": "not-generated",
                    "reason": f"skipped (--only {args.only})",
                }
            entries.append(entry)

    manifest = {
        "schema_version": SCHEMA_VERSION,
        "generator": "fixtures/generate.py",
        "tools": {
            "ffmpeg": ffmpeg_version_line(),
            "python": platform.python_version(),
        },
        "redistribution": REDISTRIBUTION,
        "fixtures": entries,
    }
    write_json(ASSETS_DIR / "manifest.json", manifest)
    write_json(COMMITTED_MANIFEST, manifest)

    shutil.rmtree(WORK_DIR, ignore_errors=True)

    generated = [e for e in entries if e["status"] == "generated"]
    missing = [e for e in entries if e["status"] != "generated"]
    total = sum(f["size_bytes"] for e in generated for f in e["files"])
    print(f"generated {len(generated)} fixtures, {total / 1e6:.1f} MB")
    for e in missing:
        print(f"not generated: {e['id']}: {e['reason']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
